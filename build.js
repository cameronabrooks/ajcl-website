// Builds the static AJCL website into dist/.
//   data/league.json  <- pushed automatically by the AJCL bot
//   content.json      <- league text you edit by hand
//   public/           <- stylesheet, scripts, AJCL logo, team logos (logos/<ABBR>.png)
// Set SITE_BASE=/ajcl-website when hosting under a GitHub Pages project path.
//
// Pages are also re-rendered in the browser when the live feed (content.json ->
// liveUrl, the ajcl-live Cloudflare Worker) has newer data, using the same
// src/render.js + src/league.js bundled into dist/app.js.
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const render = require('./src/render');
const { hydrate, renderPage } = require('./src/league');

const ROOT = __dirname;
const DIST = path.join(ROOT, 'dist');
const PUBLIC = path.join(ROOT, 'public');

const readJson = f => JSON.parse(fs.readFileSync(path.join(ROOT, f), 'utf8'));

function write(rel, html) {
  const file = path.join(DIST, rel);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, html);
}

// Wraps a CommonJS module from src/ so it runs in the browser.
function browserModule(file) {
  const code = fs.readFileSync(path.join(ROOT, 'src', file), 'utf8');
  return `(function () { var module = { exports: {} }; var exports = module.exports;\n${code}\nreturn module.exports; })()`;
}

function build() {
  const raw = readJson('data/league.json');
  const logos = fs.readdirSync(path.join(PUBLIC, 'logos')).filter(f => f.endsWith('.png')).map(f => f.slice(0, -4));
  const logoSet = new Set(logos);
  const league = hydrate(raw, abbr => logoSet.has(abbr));
  const content = readJson('content.json');

  const settings = {
    base: process.env.SITE_BASE || '',
    // Public OAuth2 client ID for "Log in with Discord" (the bot publishes it).
    discordClientId: process.env.DISCORD_CLIENT_ID || league.discordClientId || content.discordClientId || '',
    liveUrl: process.env.LIVE_URL ?? content.liveUrl ?? '',
    // Official address; Discord login always returns here (must be registered in Discord).
    siteUrl: process.env.SITE_URL ?? content.siteUrl ?? '',
    dataVersion: raw.generatedAt || 0,
  };

  // Browser bundle: templates + hydrate + the settings/content they need.
  const appJs = `// Generated by build.js. Lets live.js re-render pages in the browser.
window.AJCL = (function () {
  var render = ${browserModule('render.js')};
  var league = ${browserModule('league.js')};
  var content = ${JSON.stringify(content)};
  var logos = ${JSON.stringify(logos)};
  return { render: render, hydrate: league.hydrate, renderPage: league.renderPage, content: content, logos: logos };
})();
`;

  // Cache-busting tag covering every script and the stylesheet.
  const assetHash = crypto.createHash('sha1');
  for (const f of ['style.css', 'account.js', 'live.js']) assetHash.update(fs.readFileSync(path.join(PUBLIC, f)));
  assetHash.update(appJs);
  render.configure({ ...settings, cssVersion: assetHash.digest('hex').slice(0, 8) });

  fs.rmSync(DIST, { recursive: true, force: true });
  fs.cpSync(PUBLIC, DIST, { recursive: true });
  fs.writeFileSync(path.join(DIST, 'app.js'), appJs);

  write('index.html', renderPage(render, league, content, 'home'));
  write('schedule/index.html', renderPage(render, league, content, 'schedule'));
  write('standings/index.html', renderPage(render, league, content, 'standings'));
  write('teams/index.html', renderPage(render, league, content, 'teams'));
  for (const team of league.teams) write(`teams/${team.slug}/index.html`, renderPage(render, league, content, `team:${team.slug}`));
  write('players/index.html', renderPage(render, league, content, 'players'));
  write('draft/index.html', renderPage(render, league, content, 'draft'));
  write('power-rankings/index.html', renderPage(render, league, content, 'power-rankings'));
  for (const m of league.matches) write(`matches/${render.matchId(m)}/index.html`, renderPage(render, league, content, `match:${render.matchId(m)}`));
  for (const player of league.players) write(`players/${player.slug}/index.html`, renderPage(render, league, content, `player:${player.slug}`));
  write('join/index.html', renderPage(render, league, content, 'join'));
  write('stats/index.html', render.statsPage(league, content));
  write('auth/index.html', render.authPage(content));
  write('404.html', render.notFound(content));
  // Hashed member -> team index used after "Log in with Discord" (no raw Discord IDs).
  fs.writeFileSync(path.join(DIST, 'members.json'), JSON.stringify({
    teams: Object.fromEntries(league.teams.map(t => [t.slug, t.name])),
    members: league.members || {},
    // "team|display name" -> player page slug, for the account menu's "My Profile".
    profiles: Object.fromEntries((league.players || []).map(p => [`${p.team}|${p.name}`, p.slug])),
  }));
  fs.writeFileSync(path.join(DIST, '.nojekyll'), '');

  console.log(`Built ${league.teams.length} teams, ${league.matches.length} matches -> dist/ (data from ${raw.generatedAt ? new Date(raw.generatedAt).toISOString() : 'unknown'})`);
}

if (require.main === module) build();
module.exports = { build };
